class Canvas:
    def __init__(self, w: int, h: int):
        self.w, self.h = w, h
        self.px = [[0] * w for _ in range(h)]

    def set(self, x: int, y: int, v: int = 1) -> None:
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y][x] = v

    def fill(self, x0: int, y0: int, x1: int, y1: int, v: int = 1) -> None:
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, v)

    def box(self, x0: int, y0: int, x1: int, y1: int) -> None:
        self.fill(x0, y0, x1, y0)
        self.fill(x0, y1, x1, y1)
        self.fill(x0, y0, x0, y1)
        self.fill(x1, y0, x1, y1)

    def wave(self, y0: float, amp: float, period: float, phase: float, thick: int = 2,
             dash: int = 0) -> None:
        prev = None
        for x in range(self.w):
            y = round(y0 - amp * math.sin(2 * math.pi * (x + phase) / period))
            lo, hi = (y, y) if prev is None else (min(y, prev), max(y, prev))
            prev = y
            if dash and (x // dash) % 2:
                continue
            for yy in range(lo, hi + thick):
                self.set(x, yy)

    def ellipse(self, cx: float, cy: float, rx: float, ry: float, lo: float = 0, hi: float = 360) -> None:
        for t in range(int(lo * 4), int(hi * 4)):
            a = math.radians(t / 4)
            self.set(round(cx + rx * math.cos(a)), round(cy - ry * math.sin(a)))

    def line(self, x0: int, y0: int, x1: int, y1: int, thick: int = 1) -> None:
        n = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(n + 1):
            x, y = round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n)
            self.fill(x, y, x + thick - 1, y)

    def rows(self) -> list[str]:
        ys = [y for y in range(self.h) if any(self.px[y])]
        xs = [x for x in range(self.w) if any(self.px[y][x] for y in range(self.h))]
        return ["".join("#" if self.px[y][x] else "." for x in range(xs[0], xs[-1] + 1))
                for y in range(ys[0], ys[-1] + 1)]


def _perc(c: Canvas) -> None:            # the Machinedrum: a stick on a drum
    c.line(23, 0, 14, 9, thick=2)
    c.fill(11, 9, 14, 12)
    for x0, y0, x1, y1 in ((9, 7, 6, 4), (6, 10, 2, 8), (11, 5, 11, 1)):
        c.line(x0, y0, x1, y1)
    c.ellipse(12, 16, 11, 3)
    c.ellipse(12, 19, 11, 2.5, 180, 360)
    c.fill(1, 16, 1, 19)
    c.fill(23, 16, 23, 19)
    for x in range(4, 22, 4):
        c.fill(x, 19, x, 21)


def _dens(c: Canvas) -> None:            # DENS: lines dense at the left, thinning into dots
    s = 0x2545
    for x in range(26):
        s = (s * 1103515245 + 12345) & 0x7FFFFFFF
        h = max(1, 18 - x * 2 // 3 + (s >> 16) % 5 - 2)
        if x % 2:
            h = h // 3
        c.fill(x, 21 - h, x, 21)
        for _ in range(3):
            s = (s * 1103515245 + 12345) & 0x7FFFFFFF
            y = (s >> 16) % 22
            if y < 21 - h - 1 and (s >> 8) % 3 == 0:
                c.set(x, y)


def _art(name: str):
    def draw(c: Canvas) -> None:
        for y, row in enumerate(ART[name]):
            for x, ch in enumerate(row):
                if ch == "#":
                    c.set(x, y)
    return draw


