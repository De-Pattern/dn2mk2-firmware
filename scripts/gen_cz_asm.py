"""Write `csrc/waverider/sharc/cz.asm`: CZ (machine type 7) on the DSP, generated from one
template the way `scripts/gen_rings_asm.py` writes RESONATOR (and with PING's helpers).

    python scripts/gen_cz_asm.py

The code mirrors `dnfw.cz.live` operation by operation, in its order, so the SHARC gate
holds it to that module bit for bit. Branch targets are `0x0` with a `// -> label.`
comment; `scripts/sharc_resolve_jumps.py` fills them in. Instruction forms: only those
PING, RESONATOR and Waverider's loop already use (no XOR, no hardware loops, no CALL,
every integer add R8-R15 first). The wave code is written once and entered for each
line, its way back chosen by a scratch word.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import gen_ping_asm as G                             # noqa: E402
from dnfw.cz import live as CL                       # noqa: E402
from dnfw.waverider import dsp                       # noqa: E402

OUT = ROOT / "csrc" / "waverider" / "sharc" / "cz.asm"
emit, fconst, label, jump, place, recip, clamp01 = (G.emit, G.fconst, G.label, G.jump,
                                                    G.place, G.recip, G.clamp01)
_f32 = CL._f32

_, CAT = CL.tables_bytes()
CTAB = {name: dsp.CZ_TABLES_DDR + off for name, off in CAT.items()}

SC = dsp.CZ_SCRATCH_DM
WORDS = ("t", "count", "buf", "sbase", "i146", "sel", "mod", "sus", "dcw", "wa", "wb",
         "inc1", "inc2", "ph1", "ph2", "par1", "par2", "step", "v", "ni", "nj", "cnt", "d",
         "y1", "y", "inc2c", "ret", "k", "note", "oct", "det", "trig")
A = {w: SC + 4 * k for k, w in enumerate(WORDS)}
LV = SC + 0x80                                        # the eight levels, then the eight rates
RT = LV + 0x20
assert A[WORDS[-1]] < LV and RT + 0x20 <= SC + 0x100
# per-voice state words (dnfw.cz.live.Voice), off I2, in DDR
PH1, PH2, PAR1, PAR2, STEP, VV, NI, NJ, ACTIVE = range(9)
STATE_WORDS = 9
LOADED = (("ph1", PH1), ("ph2", PH2), ("par1", PAR1), ("par2", PAR2), ("step", STEP),
          ("v", VV), ("ni", NI), ("nj", NJ))
FRAME_BASE = 0x25C48C


def imm(v: int) -> str:
    """an address as selmap prints it: one at or above 2^31 (DDR) written signed"""
    return f"-{(1 << 32) - v:#x}" if v >> 31 else f"{v:#x}"


def ld(reg, w):
    emit(f"      R{reg} = DM({(A[w] - SC) // 4}, I5);".ljust(40) + f"// {w}")


def st(reg, w):
    emit(f"      DM({(A[w] - SC) // 4}, I5) = R{reg};".ljust(40) + f"// {w}")


def sld(reg, word):
    emit(f"      R{reg} = DM({word}, I2);")


def sst(reg, word):
    emit(f"      DM({word}, I2) = R{reg};")


def half_word(out: int) -> None:
    """R{out} = the 16-bit frame word at byte address R0. Clobbers R0-R2, I1."""
    emit("      R1 = 2;")
    emit("      R1 = R0 AND R1;")
    emit("      R2 = -4;")
    emit("      R0 = R0 AND R2;")
    emit("      I1 = R0;")
    emit(f"      R{out} = DM(0, I1);")
    emit("      R2 = -16;")
    emit("      R1 = PASS R1;")
    lo = label("zlo")
    jump("EQ", lo)
    emit(f"      R{out} = LSHIFT R{out} BY R2;")
    place(lo)
    emit("      R1 = 0xffff;")
    emit(f"      R{out} = R{out} AND R1;")


def frame_word(slot: int, out: int) -> None:
    """R{out} = the frame copy's word for param SLOT of track t (i146 in scratch).
    Clobbers R0-R2, R12, I1."""
    assert out not in (0, 1, 2, 12)
    emit(f"      // R{out} = frame word, param {slot}")
    ld(12, "i146")
    emit(f"      R0 = {FRAME_BASE + 218 + 2 * (slot - 25):#x};")
    emit("      R0 = R12 + R0;")
    half_word(out)


def enum(slot: int, count: int, out: int) -> None:
    """R{out} = min(word >> 8, count - 1)"""
    frame_word(slot, out)
    emit(f"      R{out} = LSHIFT R{out} BY -8;")
    emit(f"      R12 = {count - 1};")
    emit(f"      R{out} = MIN(R{out}, R12);")


def word_scaled(slot: int, inv: float, out: int) -> None:
    """F{out} = f32(FLOAT(frame word) * f32(inv))"""
    frame_word(slot, out)
    emit("      R12 = R12 - R12;")
    emit(f"      F{out} = FLOAT R{out} BY R12;")
    fconst(12, _f32(inv))
    emit(f"      F{out} = F{out} * F12;")


def table_interp(table: str, top: int, fx: int, out: int) -> None:
    """F{out} = live.interp(table, F{fx}) for one of CZ's DDR tables. Clobbers R0-R3,
    R12, I1; F{fx} is clamped in place."""
    emit(f"      // F{out} = {table}[F{fx}], interpolated")
    emit("      R12 = R12 - R12;")
    emit(f"      F{fx} = MAX(F{fx}, F12);")
    fconst(12, float(top))
    emit(f"      F{fx} = MIN(F{fx}, F12);")
    emit(f"      R0 = TRUNC F{fx};")
    emit("      R12 = R12 - R12;")
    emit("      F1 = FLOAT R0 BY R12;")
    emit(f"      F1 = F{fx} - F1;")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R12 = {imm(CTAB[table])};".ljust(40) + f"// {table}")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      R2 = DM(0, I1);")
    emit("      R3 = DM(1, I1);")
    emit("      F3 = F3 - F2;")
    emit("      F3 = F1 * F3;")
    emit(f"      F{out} = F2 + F3;")


def rcp(fx: int, out: int) -> None:
    """F{out} = live.rcp(F{fx}) = recip(F{fx} * 256) * 256. Clobbers R12, R13, F{fx}."""
    fconst(12, 256.0)
    emit(f"      F{fx} = F{fx} * F12;")
    recip(fx, out)
    fconst(12, 256.0)
    emit(f"      F{out} = F{out} * F12;")


def knee_var() -> None:
    """F9 = live._knee(F4, F8). Clobbers F10, F11, R12, R13."""
    hi, done = label("khi"), label("kdone")
    emit("      COMP(F4, F8);")
    jump("GE", hi)
    emit("      F10 = PASS F8;")
    rcp(10, 11)
    emit("      F9 = F4 * F15;")
    emit("      F9 = F9 * F11;")
    jump("", done)
    place(hi)
    emit("      F10 = F14 - F8;")
    rcp(10, 11)
    emit("      F9 = F4 - F8;")
    emit("      F9 = F9 * F15;")
    emit("      F9 = F9 * F11;")
    emit("      F9 = F15 + F9;")
    place(done)


def width(c: float, base: str) -> None:
    """F8 = f32(base - f32(f32(c) * d)), d in F6, base F14 (1.0) or F15 (0.5)"""
    fconst(12, _f32(c))
    emit("      F8 = F12 * F6;")
    emit(f"      F8 = {base} - F8;")


def wave_code() -> None:
    """live.wave: F4 = ph, R5 = the wave, d from scratch -> F7. Then back to the line
    that came (ret)."""
    emit("")
    emit("// ---- the wave (live.wave): F4 = phase, R5 = wave 0..7, d -> F7 ----")
    place("wr_z_wave")
    ld(6, "d")
    names = ("wr_z_saw", "wr_z_sq", "wr_z_pulse", "wr_z_double", "wr_z_sawpulse")
    for w, name in enumerate(names):
        emit(f"      R12 = {w};")
        emit("      COMP(R5, R12);")
        jump("EQ", name)
    jump("", "wr_z_res")

    place("wr_z_saw")
    width(0.49, "F15")
    knee_var()
    jump("", "wr_z_cos")

    place("wr_z_sq")
    width(0.49, "F15")
    hi, go = label("sqhi"), label("sqgo")
    emit("      COMP(F4, F15);")
    jump("GE", hi)
    emit("      R10 = PASS R4;".ljust(40) + "// h = ph")
    emit("      R11 = R11 - R11;".ljust(40) + "// base 0")
    jump("", go)
    place(hi)
    emit("      F10 = F4 - F15;".ljust(40) + "// h = ph - 0.5")
    emit("      R11 = PASS R15;".ljust(40) + "// base 0.5")
    place(go)
    emit("      F3 = PASS F8;")
    rcp(3, 9)
    emit("      F10 = F10 * F9;")
    emit("      F10 = MIN(F10, F14);")
    emit("      F10 = F15 * F10;")
    emit("      F9 = F11 + F10;")
    jump("", "wr_z_cos")

    place("wr_z_pulse")
    width(0.95, "F14")
    rcp(8, 9)
    emit("      F9 = F4 * F9;")
    emit("      F9 = MIN(F9, F14);")
    jump("", "wr_z_cos")

    place("wr_z_double")
    hi = label("dhi")
    emit("      COMP(F4, F15);")
    jump("GE", hi)
    emit("      F10 = F14 + F6;")
    emit("      F9 = F4 * F10;")
    jump("", "wr_z_cos")
    place(hi)
    emit("      F10 = F14 + F6;")
    emit("      F10 = F15 * F10;")
    emit("      F11 = F14 - F6;")
    emit("      F3 = F4 - F15;")
    emit("      F3 = F3 * F11;")
    emit("      F9 = F10 + F3;")
    jump("", "wr_z_cos")

    place("wr_z_sawpulse")
    one, g, khi = label("spone"), label("spg"), label("spkhi")
    k = _f32(0.1)
    emit("      COMP(F4, F15);")
    jump("GE", one)
    fconst(12, 2.0)
    emit("      F10 = F4 * F12;")
    emit("      F10 = MIN(F10, F14);")
    fconst(12, k)
    emit("      COMP(F10, F12);")
    jump("GE", khi)
    emit("      F11 = F10 * F15;")
    fconst(12, CL.rcp(k), "rcp(0.1)")
    emit("      F11 = F11 * F12;")
    jump("", g)
    place(khi)
    emit("      F11 = F10 - F12;")
    emit("      F11 = F11 * F15;")
    fconst(12, CL.rcp(_f32(1.0 - k)), "rcp(1 - 0.1)")
    emit("      F11 = F11 * F12;")
    emit("      F11 = F15 + F11;")
    jump("", g)
    place(one)
    emit("      R11 = PASS R14;".ljust(40) + "// g = 1.0")
    place(g)
    emit("      F10 = F14 - F6;")
    emit("      F10 = F10 * F4;")
    emit("      F11 = F6 * F11;")
    emit("      F9 = F10 + F11;")

    place("wr_z_cos")
    emit("      // F7 = 0 - cos(2 pi f): the sine table at f 256 + 64")
    fconst(12, 256.0)
    emit("      F9 = F9 * F12;")
    fconst(12, 64.0)
    emit("      F9 = F9 + F12;")
    G.interp("sin", 9, 7, shft=True)
    emit("      R12 = R12 - R12;")
    emit("      F7 = F12 - F7;")
    jump("", "wr_z_back")

    place("wr_z_res")
    fconst(12, 15.0)
    emit("      F8 = F12 * F6;")
    emit("      F8 = F14 + F8;".ljust(40) + "// k")
    emit("      F8 = F8 * F4;".ljust(40) + "// x")
    emit("      R0 = TRUNC F8;")
    emit("      R12 = R12 - R12;")
    emit("      F1 = FLOAT R0 BY R12;")
    emit("      F8 = F8 - F1;")
    fconst(12, 256.0)
    emit("      F8 = F8 * F12;")
    fconst(12, 64.0)
    emit("      F8 = F8 + F12;")
    G.interp("sin", 8, 9, shft=True)
    emit("      F9 = F14 - F9;")
    emit("      F9 = F15 * F9;".ljust(40) + "// r")
    w6, w7, wgo, upos = label("res2"), label("res3"), label("resw"), label("upos")
    emit("      R12 = 6;")
    emit("      COMP(R5, R12);")
    jump("EQ", w6)
    emit("      R12 = 7;")
    emit("      COMP(R5, R12);")
    jump("EQ", w7)
    emit("      F10 = F14 - F4;".ljust(40) + "// RES1: 1 - ph")
    jump("", wgo)
    place(w6)
    fconst(12, 2.0)
    emit("      F10 = F12 * F4;")
    emit("      F10 = F10 - F14;".ljust(40) + "// u")
    emit("      R12 = R12 - R12;")
    emit("      COMP(F10, F12);")
    jump("GE", upos)
    emit("      F10 = F12 - F10;")
    place(upos)
    emit("      F10 = F14 - F10;".ljust(40) + "// RES2: 1 - |u|")
    jump("", wgo)
    place(w7)
    emit("      F10 = F14 - F4;")
    fconst(12, 2.0)
    emit("      F10 = F12 * F10;")
    emit("      F10 = MIN(F10, F14);".ljust(40) + "// RES3")
    place(wgo)
    fconst(12, 2.0)
    emit("      F9 = F12 * F9;")
    emit("      F9 = F9 * F10;")
    emit("      F7 = F9 - F14;")

    place("wr_z_back")
    ld(0, "ret")
    emit("      R12 = 1;")
    emit("      COMP(R0, R12);")
    jump("EQ", "wr_z_r1")
    jump("", "wr_z_r2")


def pick_wave(par: str) -> None:
    """R5 = wa, or wb on the pair's second cycle"""
    ld(0, par)
    ld(5, "wa")
    emit("      R0 = PASS R0;")
    a = label("pa")
    jump("EQ", a)
    ld(5, "wb")
    place(a)


def advance(ph: str, par: str, inc: str) -> None:
    ld(4, ph)
    ld(12, inc)
    emit("      F4 = F4 + F12;")
    emit("      COMP(F4, F14);")
    nw = label("nowrap")
    jump("LT", nw)
    emit("      F4 = F4 - F14;")
    ld(0, par)
    emit("      R12 = 1;")
    emit("      R0 = R12 - R0;")
    st(0, par)
    place(nw)
    st(4, ph)


def zero_state() -> None:
    ld(0, "sbase")
    emit("      I3 = R0;")
    emit("      R0 = R0 - R0;")
    emit(f"      R14 = {STATE_WORDS};")
    emit("      R15 = 1;")
    loop = label("zzero")
    place(loop)
    emit("      DM(I3, M6) = R0;")
    emit("      R14 = R14 - R15;")
    jump("NE", loop)


def silence() -> None:
    ld(0, "buf")
    emit("      I0 = R0;")
    emit("      R0 = R0 - R0;")
    emit("      R14 = 32;")
    emit("      R15 = 1;")
    loop = label("zsil")
    place(loop)
    emit("      DM(I0, M6) = R0;")
    emit("      R14 = R14 - R15;")
    jump("NE", loop)


def controls() -> None:
    emit("      // ---- controls (live.controls) ----")
    emit("      R10 = LSHIFT R9 BY 7;")
    emit("      R11 = LSHIFT R9 BY 4;")
    emit("      R10 = R10 + R11;")
    emit("      R11 = LSHIFT R9 BY 1;")
    emit("      R10 = R10 + R11;".ljust(40) + "// 146 t")
    st(10, "i146")
    G.note_into_f11()
    st(11, "note")
    # the wave pair
    word_scaled(CL.P_WAVE, 1.0 / 0x7800, 4)
    fconst(12, 33.0)
    emit("      F4 = F4 * F12;")
    emit("      R4 = TRUNC F4;")
    emit("      R12 = 32;")
    emit("      R4 = MIN(R4, R12);")
    emit("      R4 = LSHIFT R4 BY 3;")
    emit(f"      R12 = {imm(CTAB['combos'])};".ljust(40) + "// combos")
    emit("      R4 = R12 + R4;")
    emit("      I1 = R4;")
    emit("      R0 = DM(0, I1);")
    st(0, "wa")
    emit("      R0 = DM(1, I1);")
    st(0, "wb")
    # detune
    frame_word(CL.P_DET, 4)
    emit("      R12 = R12 - R12;")
    emit("      F4 = FLOAT R4 BY R12;")
    fconst(12, 16384.0)
    emit("      F4 = F4 - F12;")
    fconst(12, _f32(1.0 / 0x3C00))
    emit("      F4 = F4 * F12;")
    fconst(12, -1.0)
    emit("      F4 = MAX(F4, F12);")
    fconst(12, 1.0)
    emit("      F4 = MIN(F4, F12);")
    st(4, "det")
    enum(CL.P_SEL, 4, 4)
    st(4, "sel")
    enum(CL.P_OCT, 3, 4)
    st(4, "oct")
    enum(CL.P_MOD, 3, 4)
    st(4, "mod")
    word_scaled(CL.P_SUS, 1.0 / 0x7800, 4)
    fconst(12, 9.0)
    emit("      F4 = F4 * F12;")
    emit("      R4 = TRUNC F4;")
    emit("      R12 = 8;")
    emit("      R4 = MIN(R4, R12);")
    st(4, "sus")
    word_scaled(CL.P_DCW, 1.0 / 0x7F00, 4)
    st(4, "dcw")
    enum(CL.P_KF, 2, 5)
    emit("      R5 = PASS R5;")
    nokf = label("nokf")
    jump("EQ", nokf)
    ld(5, "note")
    fconst(12, 36.0)
    emit("      F5 = F5 - F12;")
    fconst(12, _f32(1.0 / 96.0))
    emit("      F5 = F5 * F12;")
    clamp01(5)
    fconst(12, _f32(0.6))
    emit("      F5 = F12 * F5;")
    fconst(12, 1.0)
    emit("      F5 = F12 - F5;".ljust(40) + "// kfm")
    ld(4, "dcw")
    emit("      F4 = F4 * F5;")
    st(4, "dcw")
    place(nokf)

    # the eight rates and eight levels
    emit("      R0 = R0 - R0;")
    st(0, "k")
    place("wr_z_rl")
    ld(0, "k")
    emit("      R12 = LSHIFT R0 BY 3;")
    emit("      R13 = LSHIFT R0 BY 2;")
    emit("      R12 = R12 + R13;".ljust(40) + "// 12 k")
    emit(f"      R11 = {imm(CTAB['params'])};".ljust(40) + "// params")
    emit("      R12 = R11 + R12;")
    emit("      I3 = R12;")
    emit("      R4 = DM(0, I3);".ljust(40) + "// frame offset")
    emit("      R5 = DM(1, I3);".ljust(40) + "// lo")
    emit("      R6 = DM(2, I3);".ljust(40) + "// 1 / span")
    ld(12, "i146")
    emit("      R0 = R12 + R4;")
    emit(f"      R12 = {FRAME_BASE:#x};")
    emit("      R0 = R12 + R0;")
    half_word(7)
    emit("      R12 = R12 - R12;")
    emit("      F7 = FLOAT R7 BY R12;")
    emit("      F7 = F7 - F5;")
    emit("      F7 = F7 * F6;")
    clamp01(7)
    fconst(12, 99.0)
    emit("      F7 = F7 * F12;")
    emit("      R7 = TRUNC F7;")
    ld(0, "k")
    lev, nxt = label("zlev"), label("zrlnext")
    emit("      R12 = 8;")
    emit("      COMP(R0, R12);")
    jump("GE", lev)
    emit("      R7 = LSHIFT R7 BY 2;")
    emit(f"      R12 = {imm(CTAB['rinc'])};".ljust(40) + "// rinc")
    emit("      R7 = R12 + R7;")
    emit("      I1 = R7;")
    emit("      R8 = DM(0, I1);")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R12 = {RT:#x};".ljust(40) + "// rates")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      DM(0, I1) = R8;")
    jump("", nxt)
    place(lev)
    emit("      R12 = R12 - R12;")
    emit("      F8 = FLOAT R7 BY R12;")
    fconst(12, _f32(1.0 / 99.0))
    emit("      F8 = F8 * F12;")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R12 = {LV - 32:#x};".ljust(40) + "// levels - 8 words")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      DM(0, I1) = R8;")
    place(nxt)
    ld(0, "k")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "k")
    emit("      R12 = 16;")
    emit("      COMP(R0, R12);")
    jump("LT", "wr_z_rl")

    # the lines' increments
    ld(4, "note")
    emit("      R12 = R12 - R12;")
    emit("      F4 = MAX(F4, F12);")
    fconst(12, 135.0)
    emit("      F4 = MIN(F4, F12);")
    table_interp("inc", len(CL.table_inc()) - 2, 4, 5)
    st(5, "inc1")
    ld(0, "oct")
    o1, o2, ogo = label("oup"), label("odn"), label("ogo")
    emit("      R12 = 1;")
    emit("      COMP(R0, R12);")
    jump("EQ", o1)
    emit("      R12 = 2;")
    emit("      COMP(R0, R12);")
    jump("EQ", o2)
    emit("      R12 = R12 - R12;")
    jump("", ogo)
    place(o1)
    fconst(12, 12.0)
    jump("", ogo)
    place(o2)
    fconst(12, -12.0)
    place(ogo)
    ld(4, "note")
    emit("      F4 = F4 + F12;")
    ld(12, "det")
    emit("      F4 = F4 + F12;")
    emit("      R12 = R12 - R12;")
    emit("      F4 = MAX(F4, F12);")
    fconst(12, 135.0)
    emit("      F4 = MIN(F4, F12);")
    table_interp("inc", len(CL.table_inc()) - 2, 4, 5)
    st(5, "inc2")


def release() -> None:
    """live.block: a note-off (frame mask 36, bit t) and no trigger sends the envelope on
    from a step at or before sustain to the step after it."""
    emit("      // ---- the note-off (frame mask 36) ----")
    norel = label("norel")
    ld(0, "trig")
    emit("      R0 = PASS R0;")
    jump("NE", norel)
    ld(9, "t")
    emit("      R0 = DM(0x25c4b0);".ljust(40) + "// mask 36: the low half")
    emit("      R1 = 0xffff;")
    emit("      R0 = R0 AND R1;")
    emit("      R2 = 1;")
    emit("      R2 = LSHIFT R2 BY R9;")
