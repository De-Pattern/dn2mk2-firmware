def build() -> str:
    G.lines.clear()
    emit("// cz.asm -- CZ, machine type 7 (docs/cz.md).")
    emit("// GENERATED by scripts/gen_cz_asm.py; do not edit by hand. The contract is")
    emit("// dnfw.cz.live, operation by operation: the SHARC gate holds this to it bit for bit.")
    emit("//")
    emit("// Entered from rings.asm's tail once a block, on to wr_ping (PING / SHFT) when done.")
    emit("// For each voice slot whose record says machine 7 it renders the block into the")
    emit("// slot's buffer, replacing it.")
    emit(f"// State: 16 x {dsp.CZ_STATE_STRIDE} bytes in DDR at {dsp.CZ_STATE_DDR:#x}; scratch {SC:#x};")
    emit(f"// tables {dsp.CZ_TABLES_DDR:#x} (DDR).")
    emit("")
    emit(".SECTION/PM seg_pmco;")
    emit("")
    emit(".GLOBAL wr_cz.;")
    emit("wr_cz.:")
    emit(f"      R0 = {SC:#x};")
    emit("      I5 = R0;".ljust(40) + "// the scratch block (I5 is restored at wr_ping's end)")
    emit("      R0 = R0 - R0;")
    st(0, "t")
    st(0, "count")
    emit(f"      R0 = DM({G.SAVE + 0x24:#x});".ljust(40) + "// the block size")
    emit("      R12 = 32;")
    emit("      COMP(R0, R12);")
    jump("NE", "wr_z_done")
    place("wr_z_track")
    ld(9, "t")
    G.record_base()
    emit("      R0 = DM(109, I4);".ljust(40) + "// the record's machine type (+0x1b4)")
    emit(f"      R12 = {CL.MACHINE_TYPE};")
    emit("      COMP(R0, R12);")
    jump("NE", "wr_z_next")
    emit("      R12 = LSHIFT R9 BY 6;")
    v = dsp.CZ_STATE_DDR
    emit(f"      R11 = {imm(v)};".ljust(40) + f"// {v:#x}, written signed as selmap prints it")
    emit("      R12 = R11 + R12;")
    emit("      I2 = R12;".ljust(40) + "// this voice's state")
    st(12, "sbase")
    emit("      R12 = LSHIFT R9 BY 2;")
    emit("      R11 = 0x254a60;".ljust(40) + "// the track buffers")
    emit("      R12 = R11 + R12;")
    emit("      I1 = R12;")
    emit("      R0 = DM(0, I1);")
    st(0, "buf")
    ld(0, "count")
    emit(f"      R12 = {CL.MAX_VOICES};")
    emit("      COMP(R0, R12);")
    jump("GE", "wr_z_capped")
    # trigger
    emit("      R0 = DM(0x25c4ac);")
    emit("      R0 = LSHIFT R0 BY -16;".ljust(40) + "// TRIG_NOTE")
    emit("      R2 = 1;")
    emit("      R2 = LSHIFT R2 BY R9;")
    emit("      R0 = R0 AND R2;")
    st(0, "trig")
    emit("      R0 = PASS R0;")
    notrig = label("znotrig")
    jump("EQ", notrig)
    emit("      R0 = R0 - R0;")
    for k in (PH1, PH2, PAR1, PAR2, STEP, VV):
        sst(0, k)
    emit("      R0 = 1;")
    sst(0, ACTIVE)
    place(notrig)
    sld(0, ACTIVE)
    emit("      R0 = PASS R0;")
    jump("EQ", "wr_z_quiet")
    controls()
    release()
    samples()
    ld(0, "count")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "count")
    jump("", "wr_z_next")

    wave_code()

    emit("")
    place("wr_z_capped")
    zero_state()
    place("wr_z_quiet")
    silence()

    place("wr_z_next")
    ld(0, "t")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "t")
    emit("      R12 = 16;")
    emit("      COMP(R0, R12);")
    jump("LT", "wr_z_track")
    place("wr_z_done")
    emit(f"      JUMP {dsp.PING_SW:#x};".ljust(40) + "// ping.asm's wr_ping")
    emit(".wr_cz..end:")
    emit("      .type wr_cz.,STT_FUNC;")
    return "\n".join(G.lines) + "\n"


def main() -> int:
    text = build()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    n = sum(1 for ln in text.splitlines() if ln.startswith("      ") and not ln.strip().startswith("//"))
    print(f"wrote {OUT.relative_to(ROOT)}: {n} instructions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
