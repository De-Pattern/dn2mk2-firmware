"""Write `csrc/waverider/sharc/rings.asm`: RESONATOR (machine type 6) on the DSP, generated
from one template the way `scripts/gen_ping_asm.py` writes PING (and with its helpers).

    python scripts/gen_rings_asm.py

The code mirrors `dnfw.rings.live` operation by operation, in its order, so the SHARC
gate holds it to that module bit for bit. Branch targets are `0x0` with a `// -> label.`
comment; `scripts/sharc_resolve_jumps.py` fills them in. Instruction forms: only those
PING and Waverider's loop already use (no XOR, no hardware loops, every add R8-R15
first).
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import gen_ping_asm as G                             # noqa: E402
from dnfw.rings import live as RL                    # noqa: E402
from dnfw.waverider import dsp                       # noqa: E402

OUT = ROOT / "csrc" / "waverider" / "sharc" / "rings.asm"
emit, fconst, label, jump, place, knee, recip, clamp01 = (G.emit, G.fconst, G.label, G.jump,
                                                          G.place, G.knee, G.recip, G.clamp01)

_, RAT = RL.tables_bytes()
RTAB = {name: dsp.RINGS_TABLES_DDR + off for name, off in RAT.items()}
RTAB["sin"] = G.STAB["sin"]                          # SHFT's sine table
RTAB["rnd"] = dsp.W2_RND_DM                          # W2's random table
RTAB["pow2"] = G.STAB["pow2"]                        # SHFT's 2^((i - 64) / 12)
RLEN = {name: len(t) for name, t in RL.tables().items()}

SC = dsp.RINGS_SCRATCH_DM
X, ACC, W0 = SC, SC + 0x80, SC + 0x100
WORDS = ("t", "count", "pitch", "frac", "a0addr", "l0", "kexp", "pos", "mix", "hit", "lev",
         "tilt_g", "minc", "mnorm", "nlp_a", "n", "tilt", "peak", "buf", "b", "semi", "q",
         "cw", "sw", "g", "cnt", "sbase", "i146", "asum")
A = {w: W0 + 4 * k for k, w in enumerate(WORDS)}
assert A[WORDS[-1]] < SC + 0x200
# per-voice state words (dnfw.rings.live.Voice), off I2 / I3
Y1, Y2, ACTIVE, EXC, NENV, NLP, NI, NJ = 0, RL.MODES, 48, 49, 50, 51, 52, 53
STATE_WORDS = 54
FRAME_BASE = 0x25C48C


def imm(v: int) -> str:
    """an address as selmap prints it: one at or above 2^31 (DDR) written signed"""
    return f"-{(1 << 32) - v:#x}" if v >> 31 else f"{v:#x}"


def ld(reg, w):
    emit(f"      R{reg} = DM({A[w]:#x});".ljust(40) + f"// {w}")


def st(reg, w):
    emit(f"      DM({A[w]:#x}) = R{reg};".ljust(40) + f"// {w}")


def interp_at(table: str, fx: int, out: int) -> None:
    """F{out} = live.interp(table, F{fx}). Clobbers R0-R3, R12, I1; clamps F{fx}."""
    top = RLEN[table] - 2
    emit(f"      // F{out} = {table}[F{fx}], interpolated")
    emit("      R12 = R12 - R12;")
    emit(f"      F{fx} = MAX(F{fx}, F12);")
    fconst(12, float(top))
    emit(f"      F{fx} = MIN(F{fx}, F12);")
    emit(f"      R0 = TRUNC F{fx};")
    emit("      R12 = R12 - R12;")
    emit("      F1 = FLOAT R0 BY R12;")
    emit(f"      F1 = F{fx} - F1;")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R12 = {imm(RTAB[table])};".ljust(40) + f"// {table}")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      R2 = DM(0, I1);")
    emit("      R3 = DM(1, I1);")
    emit("      F3 = F3 - F2;")
    emit("      F3 = F1 * F3;")
    emit(f"      F{out} = F2 + F3;")


def frame_word(slot: int, out: int) -> None:
    """R{out} = the frame copy's 16-bit word for param SLOT of track t (R10 = 146 t).
    Clobbers R0-R2, R12, I1 (OUT must not be one of them)."""
    assert out not in (0, 1, 2, 12)
    emit(f"      // R{out} = frame word, param {slot}")
    emit(f"      R12 = {FRAME_BASE + 218 + 2 * (slot - 25):#x};")
    emit("      R0 = R12 + R10;")
    emit("      R1 = 2;")
    emit("      R1 = R0 AND R1;")
    emit("      R2 = -4;")
    emit("      R0 = R0 AND R2;")
    emit("      I1 = R0;")
    emit(f"      R{out} = DM(0, I1);")
    emit("      R2 = -16;")
    emit("      R1 = PASS R1;")
    lo = label("rlo")
    jump("EQ", lo)
    emit(f"      R{out} = LSHIFT R{out} BY R2;")
    place(lo)
    emit("      R1 = 0xffff;")
    emit(f"      R{out} = R{out} AND R1;")


def word_float(slot: int, inv: float, out: int, clamp: bool) -> None:
    """F{out} = FLOAT(frame word) * f32(inv), clamped to 0..1 if CLAMP."""
    frame_word(slot, out)
    emit("      R12 = R12 - R12;")
    emit(f"      F{out} = FLOAT R{out} BY R12;")
    fconst(12, RL._f32(inv))
    emit(f"      F{out} = F{out} * F12;")
    if clamp:
        clamp01(out)


def zero_state() -> None:
    """The voice's 54 state words, at sbase, to zero (Voice.__init__)."""
    ld(0, "sbase")
    emit("      I3 = R0;")
    emit("      R0 = R0 - R0;")
    emit(f"      R14 = {STATE_WORDS};")
    emit("      R15 = 1;")
    loop = label("rzero")
    place(loop)
    emit("      DM(I3, M6) = R0;")
    emit("      R14 = R14 - R15;")
    jump("NE", loop)


def silence() -> None:
    """The track buffer's 32 samples to zero."""
    ld(0, "buf")
    emit("      I0 = R0;")
    emit("      R0 = R0 - R0;")
    emit("      R14 = 32;")
    emit("      R15 = 1;")
    loop = label("rsil")
    place(loop)
    emit("      DM(I0, M6) = R0;")
    emit("      R14 = R14 - R15;")
    jump("NE", loop)


def sld(reg, word):
    emit(f"      R{reg} = DM({word}, I2);")


def sst(reg, word):
    emit(f"      DM({word}, I2) = R{reg};")


def build() -> str:
    G.lines.clear()
    emit("// rings.asm -- RESONATOR, machine type 6 (docs/rings.md).")
    emit("// GENERATED by scripts/gen_rings_asm.py; do not edit by hand. The contract is")
    emit("// dnfw.rings.live, operation by operation: the SHARC gate holds this to it bit for bit.")
    emit("//")
    emit("// Entered from machine5_live.asm's tail once a block (after every machine has")
    emit("// rendered), on to wr_cz (then PING / SHFT) when done. For each voice slot whose record")
    emit("// says machine 6 it renders the block into the slot's buffer, replacing it.")
    emit(f"// State: 16 x {dsp.RINGS_STATE_STRIDE} bytes in DDR at {dsp.RINGS_STATE_DDR:#x}; scratch {SC:#x};")
    emit(f"// tables {dsp.RINGS_TABLES_DDR:#x} (DDR).")
    emit("")
    emit(".SECTION/PM seg_pmco;")
    emit("")
    emit(".GLOBAL wr_rings.;")
    emit("wr_rings.:")
    emit("      R0 = R0 - R0;")
    st(0, "t")
    st(0, "count")
    emit(f"      R0 = DM({G.SAVE + 0x24:#x});".ljust(40) + "// the block size")
    emit("      R12 = 32;")
    emit("      COMP(R0, R12);")
    jump("NE", "wr_r_done")
    place("wr_r_track")
    ld(9, "t")
    G.record_base()
    emit("      R0 = DM(109, I4);".ljust(40) + "// the record's machine type (+0x1b4)")
    emit(f"      R12 = {RL.MACHINE_TYPE};")
    emit("      COMP(R0, R12);")
    jump("NE", "wr_r_next")
    emit("      R12 = LSHIFT R9 BY 8;")
    v = dsp.RINGS_STATE_DDR
    emit(f"      R11 = -{(1 << 32) - v:#x};".ljust(40) + f"// {v:#x}, written signed as selmap prints it")
    emit("      R12 = R11 + R12;")
    emit("      I2 = R12;".ljust(40) + "// this voice's state")
    st(12, "sbase")
    emit("      R12 = LSHIFT R9 BY 2;")
    emit("      R11 = 0x254a60;".ljust(40) + "// the track buffers")
    emit("      R12 = R11 + R12;")
    emit("      I1 = R12;")
    emit("      R0 = DM(0, I1);")
    st(0, "buf")
    ld(0, "count")
    emit(f"      R12 = {RL.MAX_VOICES};")
    emit("      COMP(R0, R12);")
    jump("GE", "wr_r_capped")
    # trigger
    emit("      R0 = DM(0x25c4ac);")
    emit("      R0 = LSHIFT R0 BY -16;".ljust(40) + "// TRIG_NOTE")
    emit("      R2 = 1;")
    emit("      R2 = LSHIFT R2 BY R9;")
    emit("      R0 = R0 AND R2;")
    notrig = label("rnotrig")
    jump("EQ", notrig)
    emit("      R0 = 1;")
    sst(0, ACTIVE)
    emit("      R0 = R0 - R0;")
    sst(0, EXC)
    sst(0, NLP)
    fconst(0, 1.0)
    sst(0, NENV)
    place(notrig)
    sld(0, ACTIVE)
    emit("      R0 = PASS R0;")
    jump("EQ", "wr_r_quiet")

    # ---- controls (live.controls) ----
    emit("      R10 = LSHIFT R9 BY 7;")
    emit("      R11 = LSHIFT R9 BY 4;")
    emit("      R10 = R10 + R11;")
    emit("      R11 = LSHIFT R9 BY 1;")
    emit("      R10 = R10 + R11;".ljust(40) + "// 146 t")
    st(10, "i146")
    G.note_into_f11()
    ld(10, "i146")
    frame_word(RL.P_TUN, 4)
    emit("      R12 = R12 - R12;")
    emit("      F4 = FLOAT R4 BY R12;")
    fconst(12, RL._f32(1.0 / 256.0))
    emit("      F4 = F4 * F12;")
    fconst(12, 64.0)
    emit("      F4 = F4 - F12;".ljust(40) + "// tun")
    emit("      F4 = F11 + F4;")
    emit("      R12 = R12 - R12;")
    emit("      F4 = MAX(F4, F12);")
    fconst(12, 127.0)
    emit("      F4 = MIN(F4, F12);")
    st(4, "pitch")
    word_float(RL.P_STRC, 1.0 / 0x7800, 4, True)
    hi_half, done = label("rhi"), label("rstdone")
    fconst(12, 0.5)
    emit("      COMP(F4, F12);")
    jump("GT", hi_half)
    fconst(12, 2.0)
    emit("      F4 = F4 * F12;")
    st(4, "frac")
    emit(f"      R0 = {imm(RTAB['anchors'])};".ljust(40) + "// anchors")
    st(0, "a0addr")
    jump("", done)
    place(hi_half)
    fconst(12, 2.0)
    emit("      F4 = F4 * F12;")
    fconst(12, 1.0)
    emit("      F4 = F4 - F12;")
    st(4, "frac")
    emit(f"      R0 = {imm(RTAB['anchors'] + 4 * RL.MODES)};".ljust(40) + "// anchors, the upper half")
    st(0, "a0addr")
    place(done)
    ld(10, "i146")
    word_float(RL.P_BRIT, 1.0 / 0x7F00, 5, True)
    fconst(12, RL._f32(0.8))
    emit("      F5 = F12 * F5;")
    fconst(12, RL._f32(0.15))
    emit("      F5 = F12 + F5;".ljust(40) + "// b")
    st(5, "b")
    ld(10, "i146")
    word_float(RL.P_DAMP, 1.0 / 0x7F00, 6, True)
    import math
    fconst(12, RL._f32(math.log2(120.0)))
    emit("      F6 = F6 * F12;")
    fconst(12, RL._f32(math.log2(6.91 / 4800.0)))
    emit("      F6 = F12 - F6;".ljust(40) + "// l0")
    st(6, "l0")
    ld(5, "b")
    fconst(12, 1.0)
    emit("      F6 = F12 - F5;")
    fconst(12, RL._f32(1.3))
    emit("      F6 = F6 * F12;")
    fconst(12, RL._f32(0.2))
    emit("      F6 = F6 + F12;".ljust(40) + "// kexp")
    st(6, "kexp")
    ld(10, "i146")
    word_float(RL.P_POS, 1.0 / 0x6400, 6, True)
    fconst(12, RL._f32(0.48))
    emit("      F6 = F12 * F6;")
    fconst(12, RL._f32(0.02))
    emit("      F6 = F12 + F6;".ljust(40) + "// pos")
    st(6, "pos")
    ld(10, "i146")
    word_float(RL.P_EXCT, 1.0 / 0x6400, 6, True)
    st(6, "mix")
    ld(10, "i146")
    word_float(RL.P_HIT, 1.0 / 0x6400, 6, False)
    st(6, "hit")
    ld(10, "i146")
    word_float(RL.P_LEV, 1.0 / 0x6400, 6, False)
    st(6, "lev")
    ld(5, "b")
    fconst(12, RL._f32(0.4))
    emit("      F6 = F12 * F5;")
    fconst(12, RL._f32(0.6))
    emit("      F6 = F12 + F6;".ljust(40) + "// tilt_g")
    st(6, "tilt_g")
    fconst(12, 1.0)
    emit("      F6 = F12 - F5;".ljust(40) + "// d")
    emit("      F6 = F6 * F6;")
    fconst(12, 0.008 * RL.RATE)
    emit("      F6 = F12 * F6;")
    fconst(12, 0.0004 * RL.RATE)
    emit("      F6 = F12 + F6;".ljust(40) + "// width")
    recip(6, 7)
    fconst(12, 128.0)
    emit("      F8 = F12 * F7;")
    st(8, "minc")
    fconst(12, 24.0)
    emit("      F8 = F12 * F7;")
    fconst(12, 1.0)
    emit("      F8 = MIN(F8, F12);")
    st(8, "mnorm")
    emit("      F6 = F5 * F5;")
    fconst(12, 12000.0)
    emit("      F6 = F6 * F12;")
    fconst(12, 300.0)
    emit("      F6 = F6 + F12;")
    fconst(12, RL._f32(2 * math.pi / RL.RATE))
    emit("      F6 = F6 * F12;")
    fconst(12, 1.0)
    emit("      F6 = MIN(F6, F12);")
    st(6, "nlp_a")

    # ---- the exciter (live.exciter) -> X ----
    emit(f"      R0 = {X:#x};")
    emit("      I0 = R0;")
    emit("      R0 = 32;")
    st(0, "cnt")
    place("wr_r_exc")
    sld(4, EXC)
    emit(f"      R12 = {RL.EXC_END};")
    emit("      COMP(R4, R12);")
    go, iend = label("rgo"), label("riend")
    jump("LT", go)
    emit("      R5 = R5 - R5;")
    emit("      DM(I0, M6) = R5;")
    jump("", iend)
    place(go)
    emit("      R12 = R12 - R12;")
    emit("      F5 = FLOAT R4 BY R12;")
    ld(12, "minc")
    emit("      F5 = F5 * F12;".ljust(40) + "// ph")
    emit("      R6 = R6 - R6;")
    nomal = label("rnomal")
    fconst(12, 128.0)
    emit("      COMP(F5, F12);")
    jump("GE", nomal)
    interp_at("sin", 5, 6)
    ld(12, "mnorm")
    emit("      F6 = F6 * F12;".ljust(40) + "// mal")
    place(nomal)
    sld(7, NI)
    sld(8, NJ)
    emit("      R0 = LSHIFT R7 BY 2;")
    emit(f"      R12 = {imm(RTAB['rnd'])};")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      R1 = DM(0, I1);")
    emit("      R13 = 255;")
    emit("      R0 = R13 - R8;".ljust(40) + "// 255 - nj")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      R2 = DM(0, I1);")
    emit("      F9 = F1 - F2;".ljust(40) + "// nz")
    emit("      R12 = 1;")
    emit("      R7 = R12 + R7;")
    emit("      R12 = 255;")
    emit("      R7 = R7 AND R12;")
    sst(7, NI)
    emit("      R12 = 1;")
    emit("      R8 = R12 + R8;")
    emit(f"      R12 = {RL.NOISE_J};")
    emit("      COMP(R8, R12);")
    njok = label("rnjok")
    jump("LT", njok)
    emit("      R8 = R8 - R8;")
    place(njok)
    sst(8, NJ)
    nonoise, noised = label("rnon"), label("rnod")
    emit(f"      R12 = {RL.NOISE_LEN};")
    emit("      COMP(R4, R12);")
    jump("GE", nonoise)
    sld(12, NENV)
    emit("      F9 = F9 * F12;")
    fconst(13, RL._f32(RL.NOISE_DECAY))
    emit("      F12 = F12 * F13;")
    sst(12, NENV)
    jump("", noised)
    place(nonoise)
    emit("      R9 = R9 - R9;")
    place(noised)
    sld(8, NLP)
    emit("      F10 = F9 - F8;")
    ld(12, "nlp_a")
    emit("      F10 = F12 * F10;")
    emit("      F8 = F8 + F10;")
    sst(8, NLP)
    ld(12, "mix")
    fconst(13, 1.0)
    emit("      F13 = F13 - F12;")
    emit("      F6 = F13 * F6;")
    fconst(13, 0.5)
    emit("      F10 = F13 * F8;")
    emit("      F10 = F12 * F10;")
    emit("      F6 = F6 + F10;")
    ld(12, "hit")
    emit("      F6 = F6 * F12;")
    emit("      DM(I0, M6) = F6;")
    emit("      R12 = 1;")
    emit("      R4 = R12 + R4;")
    sst(4, EXC)
    place(iend)
    ld(0, "cnt")
    emit("      R12 = 1;")
    emit("      R0 = R0 - R12;")
    st(0, "cnt")
    jump("NE", "wr_r_exc")

    # ---- the modes (live.coefs and the mode loop) ----
    emit(f"      R0 = {ACC:#x};")
    emit("      I4 = R0;")
    emit("      R0 = R0 - R0;")
    emit("      R14 = 32;")
    emit("      R15 = 1;")
    zl = label("rzacc")
    place(zl)
    emit("      DM(I4, M6) = R0;")
    emit("      R14 = R14 - R15;")
    jump("NE", zl)
    emit("      R0 = R0 - R0;")
    st(0, "n")
    st(0, "asum")
    fconst(0, 1.0)
    st(0, "tilt")
    place("wr_r_mode")
    ld(0, "n")
    emit(f"      R12 = {RL.MODES};")
    emit("      COMP(R0, R12);")
    jump("GE", "wr_r_modes_done")
    emit("      R1 = LSHIFT R0 BY 2;")
    ld(12, "a0addr")
    emit("      R1 = R12 + R1;")
    emit("      I1 = R1;")
    emit("      R2 = DM(0, I1);".ljust(40) + "// lo")
    emit(f"      R3 = DM({RL.MODES}, I1);".ljust(40) + "// hi")
    emit("      F3 = F3 - F2;")
    ld(12, "frac")
    emit("      F3 = F12 * F3;")
    emit("      F2 = F2 + F3;".ljust(40) + "// semi")
    st(2, "semi")
    ld(12, "pitch")
    emit("      F4 = F12 + F2;".ljust(40) + "// q")
    fconst(12, RL.TOP_NOTE)
    emit("      COMP(F4, F12);")
    jump("GE", "wr_r_modes_done")
    st(4, "q")
    interp_at("cosw", 4, 5)
    st(5, "cw")
    ld(4, "q")
    interp_at("sinw", 4, 6)
    st(6, "sw")
    ld(8, "semi")
    fconst(12, RL._f32(1.0 / 12.0))
    emit("      F8 = F8 * F12;".ljust(40) + "// lr")
    ld(12, "kexp")
    emit("      F8 = F12 * F8;")
    ld(12, "l0")
    emit("      F8 = F12 + F8;".ljust(40) + "// L")
    fconst(12, RL.L_LO)
    emit("      F8 = F8 - F12;")
    fconst(12, RL.L_STEPS)
    emit("      F8 = F8 * F12;")
    interp_at("r", 8, 7)
    emit("      R13 = PASS R7;".ljust(40) + "// R, kept (integer PASS: a bit copy)")
    ld(0, "n")
    emit("      R12 = 1;")
    emit("      R1 = R12 + R0;")
    emit("      R12 = R12 - R12;")
    emit("      F9 = FLOAT R1 BY R12;")
    ld(12, "pos")
    emit("      F9 = F9 * F12;")
    fconst(12, 128.0)
    emit("      F9 = F9 * F12;".ljust(40) + "// x")
    emit("      R10 = TRUNC F9;")
    emit("      R12 = R12 - R12;")
    emit("      F11 = FLOAT R10 BY R12;")
    emit("      F11 = F9 - F11;")
    emit("      R12 = 255;")
    emit("      R10 = R10 AND R12;")
    emit("      R12 = R12 - R12;")
    emit("      F10 = FLOAT R10 BY R12;")
    emit("      F10 = F10 + F11;".ljust(40) + "// idx")
    interp_at("sin", 10, 9)
    ld(12, "tilt")
    emit("      F9 = F9 * F12;".ljust(40) + "// amp")
    emit("      R11 = PASS R9;")
    emit("      R12 = R12 - R12;")
    emit("      COMP(F9, F12);")
    apos = label("rapos")
    jump("GE", apos)
    emit("      F11 = F12 - F9;".ljust(40) + "// |amp|")
    place(apos)
    ld(12, "asum")
    emit("      F12 = F12 + F11;")
    st(12, "asum")
    emit("      R7 = PASS R13;".ljust(40) + "// R")
    ld(5, "cw")
    emit("      F5 = F7 * F5;")
    fconst(12, 2.0)
    emit("      F4 = F12 * F5;".ljust(40) + "// a1")
    emit("      F5 = F7 * F7;".ljust(40) + "// a2")
    ld(6, "sw")
    emit("      F6 = F9 * F6;".ljust(40) + "// b0")
    ld(12, "tilt")
    ld(13, "tilt_g")
    emit("      F12 = F12 * F13;")
    st(12, "tilt")
    ld(0, "n")
    emit("      R1 = LSHIFT R0 BY 2;")
    ld(12, "sbase")
    emit("      R1 = R12 + R1;")
    emit("      I3 = R1;")
    emit(f"      R7 = DM({Y1}, I3);".ljust(40) + "// y1")
    emit(f"      R8 = DM({Y2}, I3);".ljust(40) + "// y2")
    emit(f"      R0 = {X:#x};")
    emit("      I0 = R0;")
    emit(f"      R0 = {ACC:#x};")
    emit("      I4 = R0;")
    emit("      R14 = 32;")
    emit("      R15 = 1;")
    place("wr_r_samp")
    emit("      F9 = F4 * F7;")
    emit("      F10 = F5 * F8;")
    emit("      F9 = F9 - F10;")
    emit("      R11 = DM(I0, M6);")
    emit("      F11 = F6 * F11;")
    emit("      F9 = F9 + F11;".ljust(40) + "// y")
    emit("      R8 = PASS R7;".ljust(40) + "// y2 = y1 (bit copies)")
    emit("      R7 = PASS R9;".ljust(40) + "// y1 = y")
    emit("      R12 = DM(0, I4);")
    emit("      F12 = F12 + F9;")
    emit("      DM(I4, M6) = R12;")
    emit("      R14 = R14 - R15;")
    jump("NE", "wr_r_samp")
    emit(f"      DM({Y1}, I3) = R7;")
    emit(f"      DM({Y2}, I3) = R8;")
    ld(0, "n")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "n")
    jump("", "wr_r_mode")
    place("wr_r_modes_done")

    # ---- out ----
    ld(4, "asum")
    fconst(12, RL._f32(RL.NORM))
    emit("      F4 = F12 * F4;")
    fconst(12, 1.0)
    emit("      F4 = F12 + F4;")
    recip(4, 5)
    ld(6, "lev")
    fconst(12, RL._f32(RL.OUT_GAIN))
    emit("      F6 = F6 * F12;")
    emit("      F6 = F6 * F5;".ljust(40) + "// lev OUT_GAIN norm")
    ld(8, "pitch")
    fconst(12, 60.0)
    emit("      F8 = F8 - F12;")
    fconst(12, 0.5)
    emit("      F8 = F8 * F12;")
    fconst(12, 64.0)
    emit("      F8 = F12 + F8;")
    interp_at("pow2", 8, 9)
    emit("      F6 = F6 * F9;".ljust(40) + "// g")
    st(6, "g")
    emit("      R0 = R0 - R0;")
    st(0, "peak")
    emit(f"      R0 = {ACC:#x};")
    emit("      I4 = R0;")
    ld(0, "buf")
    emit("      I0 = R0;")
    emit("      R0 = 32;")
    st(0, "cnt")
    place("wr_r_out")
    emit("      R10 = DM(I4, M6);")
    emit("      R11 = PASS R10;")
    emit("      R12 = R12 - R12;")
    emit("      COMP(F10, F12);")
    pos = label("rpos")
    jump("GE", pos)
    emit("      F11 = F12 - F10;")
    place(pos)
    ld(12, "peak")
    emit("      F12 = MAX(F12, F11);")
    st(12, "peak")
    ld(12, "g")
    emit("      F10 = F10 * F12;")
    knee(10, 0.6, 0.6)
    emit("      DM(I0, M6) = F10;")
    ld(0, "cnt")
    emit("      R12 = 1;")
    emit("      R0 = R0 - R12;")
    st(0, "cnt")
    jump("NE", "wr_r_out")
    # idle?
    alive = label("ralive")
    ld(2, "sbase")
    emit("      I2 = R2;")
    sld(0, EXC)
    emit(f"      R12 = {RL.EXC_END};")
    emit("      COMP(R0, R12);")
    jump("LT", alive)
    ld(12, "peak")
    fconst(13, RL._f32(RL.IDLE))
    emit("      COMP(F12, F13);")
    jump("GE", alive)
    zero_state()
    place(alive)
    ld(0, "count")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "count")
    jump("", "wr_r_next")

    place("wr_r_capped")
    zero_state()
    place("wr_r_quiet")
    silence()

    place("wr_r_next")
    ld(0, "t")
    emit("      R12 = 1;")
    emit("      R0 = R12 + R0;")
    st(0, "t")
    emit("      R12 = 16;")
    emit("      COMP(R0, R12);")
    jump("LT", "wr_r_track")
    place("wr_r_done")
    emit(f"      JUMP {dsp.CZ_SW:#x};".ljust(40) + "// cz.asm's wr_cz")
    emit(".wr_rings..end:")
    emit("      .type wr_rings.,STT_FUNC;")
    return "\n".join(G.lines) + "\n"


def main() -> int:
    text = build()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    n = sum(1 for ln in text.splitlines() if ln.startswith("      ") and not ln.strip().startswith("//"))
    print(f"wrote {OUT.relative_to(ROOT)}: {n} instructions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
