"""Report allocated-region headroom from the committed ColdFire image.

This reads generated bytes, not a new compilation, and cannot clear a build for
flashing. It deliberately does not infer available RAM outside declared ranges.
"""

from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def constants(module: str, names: tuple[str, ...]) -> dict[str, int]:
    # Importing the composer also loads recovered ROM resources. This audit
    # needs only literal allocation boundaries, so it never executes that code.
    source = ROOT / "src/dnfw/waverider" / module
    values = {}
    for node in ast.parse(source.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in names:
                    value = ast.literal_eval(node.value)
                    if type(value) is not int or target.id in values:
                        raise ValueError(f"{module}: ambiguous allocation {target.id}")
                    values[target.id] = value
    if set(values) != set(names):
        raise ValueError(f"{module}: missing allocation constants")
    return values


def report() -> dict:
    path = ROOT / "src/dnfw/mods/waverider_code.json"
    spec = json.loads(path.read_text(encoding="utf-8"))
    p = constants("pages.py", ("C_LOAD", "C_SPAN", "LOAD"))
    c = constants("coldfire.py", ("PAGES_END", "MCHUNK", "MCHUNK_END"))
    regions = []
    for key, label, start, end in (
        ("c_chunk", "UI and control runtime", p["C_LOAD"], p["C_LOAD"] + p["C_SPAN"]),
        ("chunk", "Page assembly", p["LOAD"], c["PAGES_END"]),
        ("machines_chunk", "Machine tables and shims", c["MCHUNK"], c["MCHUNK_END"]),
    ):
        chunk = spec[key]
        if chunk["load"] != start:
            raise ValueError(f"{label}: generated load address disagrees with source")
        used = len(bytes.fromhex(chunk["code"]))
        capacity = end - start
        if used > capacity:
            raise ValueError(f"{label}: generated image exceeds declared region")
        regions.append(dict(name=label, used_bytes=used, capacity_bytes=capacity,
                            remaining_bytes=capacity - used))
    return dict(source=str(path.relative_to(ROOT)), os=spec["os"], regions=regions,
                native_bridge="sc_capture" in spec.get("layout", {}),
                scope="Generated image allocations only. "
                      "Not whole-device free memory, source freshness or hardware validation.")


if __name__ == "__main__":
    print(json.dumps(report(), indent=2))
