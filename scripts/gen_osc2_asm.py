"""Write `csrc/waverider/sharc/osc2.asm`: Waverider's osc 2 (W3, docs/w3-osc2.md).

    python scripts/gen_osc2_asm.py

machine5_live.asm jumps here once a type-5 track's osc 1 is in its buffer (after the
W2 gain ramp); this renders osc 2 through the same reader (wr_render5) into a buffer of
its own and adds it, ramped by its gain, then jumps back to the loop's wr_t5v_next.
`dnfw.waverider.live.render_blocks` is the contract, operation by operation (Osc2,
detuned, osc2_gain, ramp), and the SHARC gate holds this to it bit for bit.

With LEV (CHAR) at 0 -- every sound saved before W3 -- it only rests the gain at 0 and
goes back: osc 1 is untouched.

Branch targets are `0x0` with a `// -> label.` comment (scripts/sharc_resolve_jumps.py
fills them in); the jump back into machine5_live.asm is written as an address, checked
against that object's own layout by test_waverider_dsp.py. Instruction forms: only
those Waverider's loop already uses.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import gen_ping_asm as G                             # noqa: E402
from dnfw.waverider import dsp                       # noqa: E402

OUT = ROOT / "csrc" / "waverider" / "sharc" / "osc2.asm"
OUT_B = ROOT / "csrc" / "waverider" / "sharc" / "osc2b.asm"
emit, label, jump, place = G.emit, G.label, G.jump, G.place

FRAME = 0x25C48C
OFF = {"tun2": 230, "wav2": 232, "ofs2": 236, "pd2": 238, "base": 256, "char": 262}
NOTE1, CHAR, G2, TRIG = (dsp.OSC2_SCRATCH_DM + 4 * k for k in range(4))
BLOCK = dsp.OSC2_BLOCK_DM


def half(name: str) -> None:
    """R0 = the frame's 16-bit word NAME for track R9 (R10 = 146t, R7 = -16, R6 = 0xffff).
    Clobbers R1, R2, R11, I1."""
    lo = label(f"{name}_lo")
    emit(f"      R11 = {FRAME + OFF[name]:#x};".ljust(40) + f"// {name}: 0x25c48c + {OFF[name]}")
    emit("      R0 = R11 + R10;".ljust(40) + "// + 146t")
    emit("      R1 = 2;")
    emit("      R1 = R0 AND R1;".ljust(40) + "// 2: the high half")
    emit("      R2 = -4;")
    emit("      R0 = R0 AND R2;")
    emit("      I1 = R0;")
    emit("      R0 = DM(0, I1);")
    emit("      R1 = PASS R1;")
    jump("EQ", lo)
    emit("      R0 = LSHIFT R0 BY R7;")
    place(lo)
    emit("      R0 = R0 AND R6;")


def track() -> None:
    """R9 = t, R10 = 146t, R7 = -16, R6 = 0xffff, I2 = this voice's osc 2 state."""
    emit("      R0 = DM(0x2dde80);")
    emit("      R1 = 16;")
    emit("      R9 = R1 - R0;".ljust(40) + "// t")
    emit("      R10 = LSHIFT R9 BY 7;")
    emit("      R11 = LSHIFT R9 BY 4;")
    emit("      R10 = R10 + R11;")
    emit("      R11 = LSHIFT R9 BY 1;")
    emit("      R10 = R10 + R11;".ljust(40) + "// 146t")
    emit("      R7 = -16;")
    emit("      R6 = 0xffff;")
    emit(f"      R12 = LSHIFT R9 BY {dsp.OSC2_STATE_STRIDE.bit_length() - 1};")
    emit(f"      R11 = {dsp.OSC2_STATE_DM:#x};")
    emit("      R12 = R11 + R12;")
    emit("      I2 = R12;".ljust(40) + "// osc 2 state: phase, s, gp")


def w2_word(k: int, reg: int) -> None:
    """R<reg> = word K of this voice's W2 state (13: u, 14: s). Clobbers R11, R12, I1."""
    emit("      R12 = LSHIFT R9 BY 6;")
    emit(f"      R11 = {dsp.W2_STATE_DM:#x};")
    emit("      R12 = R11 + R12;")
    emit("      I1 = R12;")
    emit(f"      R{reg} = DM({k}, I1);")


def depth(reg_word: int) -> None:
    """F0 = (R<reg_word> - 0x3200) / 0x3200, as live.depth. Clobbers R1."""
    emit("      R1 = 0x3200;")
    emit(f"      R5 = R{reg_word} - R1;".ljust(40) + "// signed, the centre is 0")
    emit("      R1 = R1 - R1;")
    emit("      F0 = FLOAT R5 BY R1;")
    emit("      R1 = 0x38a3d70a;".ljust(40) + "// 1 / 0x3200")
    emit("      F0 = F0 * F1;".ljust(40) + "// depth, -1..+1")


def loop_next() -> int:
    """machine5_live.asm's wr_t5v_next as a short-word address, from its committed
    object (refused if that object is stale for the source)."""
    import json
    import hashlib
    import sharc_resolve_jumps as R
    src = ROOT / "csrc" / "waverider" / "sharc" / "machine5_live.asm"
    spec = json.loads(src.with_suffix(".json").read_text(encoding="utf-8"))
    text = src.read_text(encoding="utf-8")
    if spec["source_sha256"] != hashlib.sha256(text.replace("\r\n", "\n").encode()).hexdigest():
        raise SystemExit("machine5_live.json is stale: assemble it first")
    k = R.labels(text)["wr_t5v_next"]
    return int(spec["load_sw"], 16) + spec["instruction_offsets"][k] // 2


def build() -> tuple[str, str]:
    """-> (osc2.asm, osc2b.asm): one routine in two places, L1's free gaps being what
    they are. The first jumps to the second."""
    G.lines.clear()
    emit("// osc2.asm -- Waverider's osc 2 (W3, docs/w3-osc2.md).")
    emit("// GENERATED by scripts/gen_osc2_asm.py; do not edit by hand. The contract is")
    emit("// dnfw.waverider.live.render_blocks (Osc2): the SHARC gate holds this to it bit for bit.")
    emit("//")
    emit("// Entered by machine5_live.asm's JUMP after osc 1's gain ramp, for a type-5 track,")
    emit("// with a block of 32; leaves by a JUMP to its wr_t5v_next. I3, I5 and M4 are the")
    emit("// loop's and are left alone.")
    emit(f"// State: 16 x {dsp.OSC2_STATE_STRIDE} bytes at {dsp.OSC2_STATE_DM:#x}; the reader block")
    emit(f"// {BLOCK:#x}; the buffer {dsp.OSC2_BUF_DM:#x}; scratch {dsp.OSC2_SCRATCH_DM:#x}.")
    emit("")
    emit(".SECTION/PM seg_pmco;")
    emit("")
    emit(".GLOBAL wr_osc2.;")
    emit("wr_osc2.:")
    emit("      R0 = DM(0x2dde24);".ljust(40) + "// the block size")
    emit("      R12 = 32;")
    emit("      COMP(R0, R12);")
    jump("NE", "wr_o_back")
    track()
    half("char")
    emit("      R1 = LSHIFT R0 BY -8;")
    emit("      R2 = 127;")
    emit("      R1 = MIN(R1, R2);".ljust(40) + "// LEV, 0..127")
    emit("      R1 = PASS R1;")
    jump("NE", "wr_o_on")
    emit("      R0 = R0 - R0;")
    emit("      DM(2, I2) = R0;".ljust(40) + "// off: the gain rests at 0")
    jump("", "wr_o_back")
    place("wr_o_on")
    emit(f"      DM({CHAR:#x}) = R0;")
    # trigger
    emit("      R0 = DM(0x25c4ac);")
    emit("      R0 = LSHIFT R0 BY -16;".ljust(40) + "// TRIG_NOTE")
    emit("      R2 = 1;")
    emit("      R2 = LSHIFT R2 BY R9;")
    emit("      R0 = R0 AND R2;")
    emit(f"      DM({TRIG:#x}) = R0;")
    # POS: glide, then the shared scanner's s x MPOS
    half("wav2")
    emit("      R2 = 0x7800;")
    emit("      R4 = MIN(R0, R2);")
    emit("      R4 = LSHIFT R4 BY 5;".ljust(40) + "// the target, Q16 frames")
    emit("      R14 = DM(1, I2);".ljust(40) + "// s")
    emit(f"      R0 = DM({TRIG:#x});")
    emit("      R0 = PASS R0;")
    jump("EQ", "wr_o_glide")
    emit("      R14 = PASS R4;".ljust(40) + "// a note starts at the target")
    jump("", "wr_o_glided")
    place("wr_o_glide")
    emit("      R15 = R4 - R14;")
    emit("      R12 = -5;")
    emit("      R15 = ASHIFT R15 BY R12;".ljust(40) + "// / 32, toward -inf")
    emit("      R14 = R14 + R15;")
    place("wr_o_glided")
    emit("      DM(1, I2) = R14;")
    half("ofs2")
    emit("      R3 = PASS R0;")
    depth(3)
    w2_word(14, 11)                                   # the scanner's s
    emit("      F0 = F11 * F0;")
    emit("      R1 = 0x49700000;".ljust(40) + "// 983040.0: 15 frames, Q16")
    emit("      F0 = F0 * F1;")
    emit("      R1 = R1 - R1;")
    emit("      F2 = FLOAT R14 BY R1;")
    emit("      F2 = F2 + F0;")
    emit("      F2 = MAX(F2, F1);".ljust(40) + "// >= 0.0")
    emit("      R1 = 0x49700000;")
    emit("      F2 = MIN(F2, F1);".ljust(40) + "// <= 983040.0")
    emit("      R4 = TRUNC F2;")
    emit(f"      DM({BLOCK + 12:#x}) = R4;".ljust(40) + "// pos")
    # TBL: through the lut and the directory, as osc 1
    half("base")
    emit("      R1 = LSHIFT R0 BY -8;")
    emit("      R2 = 127;")
    emit("      R1 = MIN(R1, R2);")
    emit("      R1 = LSHIFT R1 BY 2;")
    emit(f"      R12 = {dsp.LUT_DM:#x};".ljust(40) + "// the TBL -> slot table")
    emit("      R1 = R12 + R1;")
    emit("      I1 = R1;")
    emit("      R1 = DM(0, I1);")
    emit(f"      R2 = DM({dsp.DIRECTORY_DM + 4:#x});".ljust(40) + "// the directory's count")
    emit("      COMPU(R1, R2);")
    jump("LT", "wr_o_slot_ok")
    emit("      R1 = R1 - R1;")
    place("wr_o_slot_ok")
    emit("      R1 = LSHIFT R1 BY 2;")
    emit(f"      R12 = {dsp.DIRECTORY_DM + 8:#x};")
    emit("      R1 = R12 + R1;")
    emit("      I1 = R1;")
    emit("      R2 = DM(0, I1);")
    emit(f"      DM({BLOCK:#x}) = R2;".ljust(40) + "// table")
    emit("      R2 = DM(0, I2);")
    emit(f"      DM({BLOCK + 4:#x}) = R2;".ljust(40) + "// phase")
    # pitch: osc 1's note (tuned, at most 127) + DETN
    half("tun2")
    emit("      R12 = -8;")
    emit("      F13 = FLOAT R0 BY R12;".ljust(40) + "// word / 256")
    emit("      R12 = 0x42800000;".ljust(40) + "// 64.0")
    emit("      F13 = F13 - F12;")
    emit(f"      R8 = DM({NOTE1:#x});".ljust(40) + "// osc 1's note, 0..127")
    emit("      F8 = F8 + F13;")
    emit("      R8 = PASS R8;")
    jump("GE", "wr_o_pos")
    emit("      R8 = R8 - R8;".ljust(40) + "// below 0 -> +0.0")
    place("wr_o_pos")
    emit("      R12 = 0x42fe0000;".ljust(40) + "// 127.0")
    emit("      F8 = MIN(F8, F12);")
    emit("      R0 = TRUNC F8;".ljust(40) + "// k")
    emit("      R12 = R12 - R12;")
    emit("      F1 = FLOAT R0 BY R12;")
    emit("      F8 = F8 - F1;".ljust(40) + "// fr")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R12 = {dsp.INC_TABLE_DM:#x};")
    emit("      R0 = R12 + R0;")
    emit("      I1 = R0;")
    emit("      R1 = DM(0, I1);")
    emit("      R2 = DM(1, I1);")
    emit("      F2 = F2 - F1;")
    emit("      F2 = F8 * F2;")
    emit("      F1 = F1 + F2;")
    emit("      R1 = TRUNC F1;")
    emit(f"      DM({BLOCK + 8:#x}) = R1;".ljust(40) + "// inc")
    emit(f"      JUMP {dsp.OSC2B_SW:#x};".ljust(40) + "// osc2b.asm's wr_osc2b")
    place("wr_o_back")
    emit(f"      JUMP {loop_next():#x};".ljust(40) + "// machine5_live.asm's wr_t5v_next (checked by test_waverider_dsp)")
    emit(".wr_osc2..end:")
    emit("      .type wr_osc2.,STT_FUNC;")
    first = "\n".join(G.lines) + "\n"
    G.lines.clear()
    emit("// osc2b.asm -- Waverider's osc 2, continued from osc2.asm (docs/w3-osc2.md).")
    emit("// GENERATED by scripts/gen_osc2_asm.py; do not edit by hand.")
    emit("")
    emit(".SECTION/PM seg_pmco;")
    emit("")
    emit(".GLOBAL wr_osc2b.;")
    emit("wr_osc2b.:")
    track()
    emit("      R0 = 32;")
    emit(f"      DM({BLOCK + 16:#x}) = R0;".ljust(40) + "// count")
    emit(f"      R0 = {dsp.OSC2_BUF_DM:#x};")
    emit(f"      DM({BLOCK + 20:#x}) = R0;".ljust(40) + "// out: osc 2's buffer")
    # gain: LEV x the scanner's level through MLEV (PD2)
    half("pd2")
    emit("      R3 = PASS R0;")
    depth(3)
    w2_word(13, 10)                                   # the scanner's u
    emit("      R12 = 0x3f800000;")
    emit("      R5 = PASS R5;")
    jump("LT", "wr_o_mlev_neg")
    emit("      F2 = F12 - F10;".ljust(40) + "// 1 - u")
    emit("      F2 = F0 * F2;")
    emit("      F2 = F12 - F2;".ljust(40) + "// a = 1 - d (1 - u)")
    jump("", "wr_o_mlev_done")
    place("wr_o_mlev_neg")
    emit("      F2 = F0 * F10;")
    emit("      F2 = F12 + F2;".ljust(40) + "// a = 1 + d u")
    place("wr_o_mlev_done")
    emit(f"      R0 = DM({CHAR:#x});")
    emit("      R0 = LSHIFT R0 BY -8;")
    emit("      R1 = 127;")
    emit("      R0 = MIN(R0, R1);")
    emit("      R0 = LSHIFT R0 BY 2;")
    emit(f"      R11 = {dsp.W2_LEVEL_DM:#x};".ljust(40) + "// the LEV table")
    emit("      R0 = R11 + R0;")
    emit("      I1 = R0;")
    emit("      R1 = DM(0, I1);")
    emit("      F2 = F1 * F2;".ljust(40) + "// g")
    emit(f"      DM({G2:#x}) = R2;")
    emit(f"      R0 = DM({TRIG:#x});")
    emit("      R0 = PASS R0;")
    jump("EQ", "wr_o_render")
    emit("      DM(2, I2) = R2;".ljust(40) + "// a note starts at its own gain")
    place("wr_o_render")
    emit(f"      R4 = {BLOCK:#x};".ljust(40) + "// wr_render5's argument: the reader block")
    emit(f"      CJUMP {dsp.READER_SW:#x} (DB);".ljust(40) + "// wr_render5(R4 = reader block)")
    emit("      DM(I7, M7) = R2;")
    emit("      DM(I7, M7) = 0x0;".ljust(40) + "// return address - 1: wr_o_mix. - 1")
    place("wr_o_mix")
    track()
    emit(f"      R0 = DM({BLOCK + 4:#x});")
    emit("      DM(0, I2) = R0;".ljust(40) + "// the phase, for the next block")
    emit("      R1 = DM(2, I2);".ljust(40) + "// gp")
    emit(f"      R2 = DM({G2:#x});".ljust(40) + "// g")
    emit("      DM(2, I2) = R2;".ljust(40) + "// the next block starts from g")
    emit("      F3 = F2 - F1;")
    emit("      R4 = 0x3d000000;".ljust(40) + "// 1/32")
    emit("      F3 = F3 * F4;".ljust(40) + "// step")
    emit("      R0 = DM(0x2dde84);")
    emit("      I4 = R0;".ljust(40) + "// osc 1's reader block")
    emit("      R0 = DM(5, I4);")
    emit("      I1 = R0;".ljust(40) + "// the track buffer")
    emit(f"      R0 = {dsp.OSC2_BUF_DM:#x};")
    emit("      I0 = R0;".ljust(40) + "// osc 2's samples")
    emit("      R5 = 32;")
    place("wr_o_add")
    emit("      F1 = F1 + F3;")
    emit("      R0 = DM(I0, M6);")
    emit("      F0 = F0 * F1;")
    emit("      R2 = DM(0, I1);")
    emit("      F2 = F2 + F0;".ljust(40) + "// osc 1 + osc 2")
    emit("      DM(I1, M6) = F2;")
    emit("      R12 = 1;")
    emit("      R5 = R5 - R12;")
    jump("NE", "wr_o_add")
    place("wr_o_back")
    emit(f"      JUMP {loop_next():#x};".ljust(40) + "// machine5_live.asm's wr_t5v_next (checked by test_waverider_dsp)")
    emit(".wr_osc2b..end:")
    emit("      .type wr_osc2b.,STT_FUNC;")
    return first, "\n".join(G.lines) + "\n"


def main() -> int:
    for out, text in zip((OUT, OUT_B), build()):
        out.write_text(text, encoding="utf-8", newline="\n")
        n = sum(1 for ln in text.splitlines() if ln.startswith("      ") and not ln.strip().startswith("//"))
        print(f"wrote {out.relative_to(ROOT)}: {n} instructions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
